const decoded = new WeakMap<Bitmap, Uint8Array>()

const pixels = (bm: Bitmap) => {
  let px = decoded.get(bm)

  if (!px) {
    px = new Uint8Array(bm.width * bm.height)

    for (let y = 0; y < bm.height; y++) {
      for (let x = 0; x < bm.width; x++) {
        px[y * bm.width + x] = parseInt(bm.rows[y]![x]!, 16)
      }
    }

    decoded.set(bm, px)
  }

  return px
}

/** Bilinear sample in unit space, 0..1; 0 outside the map. */
export function sampleBitmap(bm: Bitmap, u: number, v: number): number {
  if (u < 0 || v < 0 || u >= 1 || v >= 1) {
    return 0
  }

  const px = pixels(bm)
  const fx = u * (bm.width - 1)
  const fy = v * (bm.height - 1)
  const x0 = Math.floor(fx)
  const y0 = Math.floor(fy)
  const x1 = Math.min(bm.width - 1, x0 + 1)
  const y1 = Math.min(bm.height - 1, y0 + 1)
  const tx = fx - x0
  const ty = fy - y0
  const top = px[y0 * bm.width + x0]! * (1 - tx) + px[y0 * bm.width + x1]! * tx
  const bot = px[y1 * bm.width + x0]! * (1 - tx) + px[y1 * bm.width + x1]! * tx

  return (top * (1 - ty) + bot * ty) / 15
}
